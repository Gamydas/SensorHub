import shutil
import vitis
import os
import subprocess
from pathlib import Path


client = vitis.create_client()

### Globals
script_folder = Path(__file__).resolve().parent
repo_root = script_folder.parent
web_dir = script_folder / "web"
fsdata_dir = repo_root / "build" / "fsdata"
# lwIP's httpd app is not built into the BSP. use the unmodified sources of the same lwip220 version the BSP uses
lwip_http_dir = Path(os.environ["XILINX_VITIS"]) / "data/embeddedsw/ThirdParty/sw_services/lwip220_v1_4/src/lwip-2.2.0/src/apps/http"
workspace = repo_root / "build" / "vitis"
### IMPORTANT: DON'T CHANGE!!!
xsa_path = str(repo_root / "hw/sensorhub.xsa")
CPU = "ps7_cortexa9_0"
OS = "freertos"
### IMPORTANT: DON'T CHANGE!!!

# Start from a clean workspace so every run reproduces the same state
shutil.rmtree(workspace, ignore_errors=True)
client.set_workspace(str(workspace))

# Convert sw/web into fsdata.c with lwIP's makefsdata, built for the host.
# makefsdata only turns files into C arrays, so empty host config headers are enough to compile it.
shutil.rmtree(fsdata_dir, ignore_errors=True)
(fsdata_dir / "hostinc" / "arch").mkdir(parents=True)
(fsdata_dir / "hostinc" / "lwipopts.h").touch()
(fsdata_dir / "hostinc" / "arch" / "cc.h").touch()
lwip_root = lwip_http_dir.parents[2]
makefsdata = fsdata_dir / "makefsdata"
subprocess.run(["gcc", "-o", str(makefsdata), str(lwip_http_dir / "makefsdata" / "makefsdata.c"),
                f"-I{lwip_root / 'src' / 'include'}", f"-I{fsdata_dir / 'hostinc'}"], check=True)
subprocess.run([str(makefsdata), str(web_dir), f"-f:{fsdata_dir / 'fsdata.c'}"], check=True)

platform = client.create_platform_component(name="sensorhub_platform", hw_design=xsa_path, os=OS, cpu=CPU)

domain = platform.get_domain(name="freertos_ps7_cortexa9_0")
domain.set_lib(lib_name="lwip220")

# Only values deviating from the lwIP defaults (taken from the FreeRTOS lwIP echo server template)
lwip_config = {
    "lwip220_api_mode": "SOCKET_API",
    "lwip220_dhcp": "true",
    "lwip220_lwip_dhcp_does_acd_check": "true",
    "lwip220_pbuf_pool_size": "2048",
}
for param, value in lwip_config.items():
    domain.set_config(option="lib", param=param, value=value, lib_name="lwip220")

# Leftover from debugging a Xil_Assert at scheduler start, the ScuTimer turned out not to be
# the cause. Kept to reproduce the last known-working BSP, test removal separately.
domain.set_config(option="lib", param="XILTIMER_tick_timer", value="ps7_ttc_0", lib_name="xiltimer")

platform.build()

# Platform export generated by platform.build(), the app is created against it
xpfm_path = str(workspace / "sensorhub_platform" / "export" / "sensorhub_platform" / "sensorhub_platform.xpfm")

app = client.create_app_component(
    name="httpd_webserver",
    platform=xpfm_path,
    domain="freertos_ps7_cortexa9_0",
    template="empty_application",
)

# Template provides CMakeLists.txt, UserConfig.cmake, lscript.ld and app.yaml (identical to the old ones).
# Sources are referenced, not copied, so edits in the Vitis GUI land in the repo.
app_src = script_folder / "httpd_webserver" / "src"
app.import_files(from_loc=str(app_src), files=["main.c"], dest_dir_in_cmp="src", is_skip_copy_sources=True)

app.import_files(from_loc=str(lwip_http_dir), files=["httpd.c", "httpd_structs.h"], dest_dir_in_cmp="src", is_skip_copy_sources=True)
# fs.c is copied, not referenced: next to the original lies lwIP's own fsdata.c, which "#include" would pick first
app.import_files(from_loc=str(lwip_http_dir), files=["fs.c"], dest_dir_in_cmp="src")

# Only settings deviating from the template's UserConfig.cmake.
# Generated fsdata.c must come before lwip_http_dir, which is still needed for fsdata.h.
app.set_app_config(key="USER_COMPILE_DEFINITIONS", values=["LWIP_HTTPD_CGI=1"])
app.set_app_config(key="USER_INCLUDE_DIRECTORIES", values=[str(fsdata_dir), str(lwip_http_dir)])

app.build()
